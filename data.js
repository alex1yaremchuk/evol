const MA_IN_YEARS = 1000000;
const yearsToMa = (years) => years / MA_IN_YEARS;

function readableYears(years) {
  if (years >= 1000000000) return `${(years / 1000000000).toFixed(2).replace(".", ",")} млрд лет`;
  if (years >= 1000000) return `${(years / 1000000).toFixed(1).replace(".", ",")} млн лет`;
  if (years >= 1000) return `${Math.round(years / 1000).toLocaleString("ru-RU")} тыс. лет`;
  return `${years.toLocaleString("ru-RU")} лет`;
}

function powerTwoLabel(power) {
  const years = 2 ** power;
  return `2^${power} лет назад (~${readableYears(years)})`;
}

